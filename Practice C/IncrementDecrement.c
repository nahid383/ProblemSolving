{
    int x=58;

    printf("%d\n",x++); //x=58
     printf("%d\n",x);  //x=59
      printf("%d\n",++x);   //x=60
       printf("%d\n",x--);  //x=60
        printf("%d\n",x--); //x=59
         printf("%d\n",x);  //x=58
          printf("%d\n",x++);         //x=58
           printf("%d\n",x++);        //x=59
            printf("%d\n",++x);       //x=61
             printf("%d\n",x--);        //x=61
              printf("%d\n",x++);     //x=60
               printf("%d\n",--x);      //x=60

               return 0;


}
