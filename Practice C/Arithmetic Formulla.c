//Arithmic operator

#include<stdio.h>
int main()
{
    int num1,num2;
    printf("Enter 1st value: ");
    scanf("%d",&num1);
    printf("Enter 2nd value: ");
    scanf("%d",&num2);

    printf("Addition will be: %d\n",num1+num2);
    printf("Substraction will be: %d\n",num1-num2);
    printf("Multiplication will be: %d\n",num1*num2);
    printf("Devidation will be: %d\n",num1/num2);
    printf("Reminder will be: %d\n",num1%num2);


    return 0;
}
